"""Writes the configuration the deploy publishes with: worker/wrangler.toml
without its [build] table.

wrangler runs [build] before `dev` and `deploy`. The deploy job holds the
Cloudflare token and must build nothing (CLAUDE.md §6): the build job, which
has no secret, builds the Worker, and the deploy job publishes that build with
this configuration. It is generated from wrangler.toml on every deploy, so the
two cannot drift; the result is parsed again and must equal wrangler.toml
without `build`, with no `build` table left anywhere (an [env.*.build] would
run too).

    python3 -I scripts/deploy-config.py worker/wrangler.toml worker/wrangler.deploy.toml
"""

import re
import sys
import tomllib

HEADER = re.compile(r"\s*\[")
# Blank and comment-only lines mean nothing to TOML: they stay, so the
# comment that opens the next table is not lost.
INERT = re.compile(r"\s*(#.*)?")
BUILD = re.compile(r"\s*\[\s*build\s*\]\s*(#.*)?")


def without_build(text):
    """The text with the lines of the [build] table removed."""
    kept, skipping = [], False
    for line in text.splitlines(keepends=True):
        if BUILD.fullmatch(line.rstrip("\r\n")):
            skipping = True
            continue
        if skipping and HEADER.match(line):
            skipping = False
        if not skipping or INERT.fullmatch(line.rstrip("\r\n")):
            kept.append(line)
    return "".join(kept)


def builds(node, path=()):
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "build":
                yield ".".join(path + (key,))
            yield from builds(value, path + (key,))
    elif isinstance(node, list):
        for index, value in enumerate(node):
            yield from builds(value, path + (str(index),))


def main(source, target):
    with open(source, encoding="utf-8") as f:
        text = f.read()
    config = tomllib.loads(text)
    output = without_build(text)
    try:
        deployed = tomllib.loads(output)
    except tomllib.TOMLDecodeError as error:
        print(f"::error file={source}::without [build] it no longer parses: {error}")
        return 1
    left = list(builds(deployed))
    if left:
        print(f"::error file={source}::{', '.join(left)}: the deploy must not build; keep the build in one [build] table")
        return 1
    expected = {key: value for key, value in config.items() if key != "build"}
    if deployed != expected:
        print(f"::error file={source}::removing [build] changed more than [build]")
        return 1
    with open(target, "w", encoding="utf-8") as f:
        f.write(
            "# Generated by scripts/deploy-config.py from wrangler.toml, without [build]:\n"
            "# the deploy publishes what the build job built. Do not edit.\n"
        )
        f.write(output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
