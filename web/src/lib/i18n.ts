export const languages = ['it', 'en', 'fr', 'es', 'de'] as const;
export type Language = (typeof languages)[number];

export const catalogs: Record<Language, Messages> = { it, en, fr, es, de };

/** The first browser language we speak, matched on its primary subtag; English otherwise. */
export function pickLanguage(preferred: readonly string[]): Language {
  for (const tag of preferred) {
    const primary = tag.toLowerCase().split('-')[0];
    const match = languages.find((l) => l === primary);
    if (match) return match;
  }
  return 'en';
}

export const language = pickLanguage(typeof navigator === 'undefined' ? [] : navigator.languages);
export const t: Messages = catalogs[language];
