export const catalogs: Record<'it' | 'en', Messages> = { it, en };

export function pickLanguage(preferred: readonly string[]): 'it' | 'en' {
  return preferred.some((l) => l.toLowerCase().startsWith('it')) ? 'it' : 'en';
}

export const language = pickLanguage(typeof navigator === 'undefined' ? [] : navigator.languages);
export const t: Messages = catalogs[language];
